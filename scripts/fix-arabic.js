/* ---------- helpers ---------- */

function normalizeTanweenOrder(text) {
  // "جداً" (alif-then-fathatan) → "جدًا" (fathatan-then-alif), corpus-wide
  return String(text ?? '').replace(/ا\u064B/g, '\u064B\u0627');
}

function fixArabicText(text) {
  if (!text || !/[\u0600-\u06FF]/.test(text)) return text;
  let out = normalizeTanweenOrder(text);
  // split into Arabic LETTER runs and separators. Arabic punctuation
  // (، ؟ ؛ U+060C/061B/061F) lives INSIDE the \u0600-\u06FF block, so the
  // class must exclude it — otherwise "عفوا،" stays one token and the
  // whole-word map never matches.
  const parts = out.split(/([\u0621-\u0655\u0670-\u06D3\u0640]+)/);
  for (let i = 0; i < parts.length; i++) {
    if (/[\u0621-\u0655\u0670-\u06D3]/.test(parts[i]) && TANWEEN_MAP[parts[i]]) {
      parts[i] = TANWEEN_MAP[parts[i]];
    }
  }
  out = parts.join('');
  for (const [re, rep] of CONTEXT_RULES) out = out.replace(re, rep);
  return out;
}

function dedupeAccepted(arr) {
  if (!Array.isArray(arr)) return arr;
  const seen = new Set();
  const out = [];
  for (const a of arr) {
    const k = String(a ?? '').trim().toLowerCase().replace(/\s+/g, ' ');
    if (seen.has(k)) continue;
    seen.add(k);
    out.push(a);
  }
  return out;
}

