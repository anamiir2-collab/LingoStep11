/* ---------- main (only when invoked directly) ---------- */

import { pathToFileURL } from 'url';
const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) main();

function main() {
let filesChanged = 0;
let tanweenFixes = 0;
let contextFixes = 0;
let dedupes = 0;
let afternoonFixes = 0;

function countFixes(before, after) {
  if (before === after) return;
  const bWords = before.split(/\s+/);
  const aWords = after.split(/\s+/);
  if (bWords.length === aWords.length) tanweenFixes += 1; else contextFixes += 1;
}

for (const entry of lessonManifest) {
  const filePath = join(ROOT, entry.path);
  const src = readFileSync(filePath, 'utf-8');
  const headerEnd = src.indexOf('export default');
  const header = src.slice(0, headerEnd);
  const body = src.slice(headerEnd).replace(/^export default\s*/, '').replace(/;\s*$/, '');
  const lesson = JSON.parse(body);
  const before = JSON.stringify(lesson);

  for (const ex of lesson.exercises) {
    // Good afternoon → طاب يومك (per spec table)
    if (ex.en && ex.en.startsWith('Good afternoon') && typeof ex.ar === 'string' && ex.ar.includes('مساء الخير')) {
      ex.ar = ex.ar.replace(/مساء الخير/g, 'طاب يومك');
      afternoonFixes += 1;
    }
    if (typeof ex.ar === 'string') { const fixed = fixArabicText(ex.ar); countFixes(ex.ar, fixed); ex.ar = fixed; }
    if (typeof ex.hint === 'string') ex.hint = fixArabicText(ex.hint);
    if (typeof ex.question === 'string') ex.question = fixArabicText(ex.question);
    if (Array.isArray(ex.options)) ex.options = ex.options.map((o) => (typeof o === 'string' ? fixArabicText(o) : o));
    if (typeof ex.explanation === 'string') ex.explanation = fixArabicText(ex.explanation);
    if (Array.isArray(ex.acceptedAnswers)) {
      const deduped = dedupeAccepted(ex.acceptedAnswers);
      if (deduped.length !== ex.acceptedAnswers.length) dedupes += deduped.length === ex.acceptedAnswers.length ? 0 : 1;
      ex.acceptedAnswers = deduped;
    }
  }
  for (const v of lesson.vocabulary) {
    if (typeof v.meaningAr === 'string') { const fixed = fixArabicText(v.meaningAr); countFixes(v.meaningAr, fixed); v.meaningAr = fixed; }
    if (typeof v.example === 'string' && /[\u0600-\u06FF]/.test(v.example)) v.example = fixArabicText(v.example);
  }
  if (lesson.grammar) {
    if (typeof lesson.grammar.explanationAr === 'string') { const f = fixArabicText(lesson.grammar.explanationAr); countFixes(lesson.grammar.explanationAr, f); lesson.grammar.explanationAr = f; }
    if (Array.isArray(lesson.grammar.examples)) for (const g of lesson.grammar.examples) {
      if (typeof g.ar === 'string') { const f = fixArabicText(g.ar); countFixes(g.ar, f); g.ar = f; }
    }
  }
  if (typeof lesson.titleAr === 'string') lesson.titleAr = fixArabicText(lesson.titleAr);

  const after = JSON.stringify(lesson);
  if (after !== before) {
    const out = `${header}export default ${JSON.stringify(lesson, null, 2)};\n`;
    writeFileSync(filePath, out, 'utf-8');
    filesChanged += 1;
  }
}

console.log('=== fix-arabic ===');
console.log(`  files rewritten: ${filesChanged}`);
console.log(`  tanween word fixes (fields): ${tanweenFixes}`);
console.log(`  context/phrase fixes (fields): ${contextFixes}`);
console.log(`  "Good afternoon" → طاب يومك: ${afternoonFixes}`);
console.log(`  acceptedAnswers lists deduped: ${dedupes}`);
}
